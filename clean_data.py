"""
clean_data.py
=============
WHAT THIS FILE DOES (plain English):

You have three real, messy Excel trackers. This script reads them, fixes the
common problems (typo'd college names, inconsistent dates, blank cells), and
writes out three CLEAN csv files that the dashboard (app.py) will read from.

It also writes a report called data_quality_report.txt that tells you exactly
what was fixed and how many rows were affected - so nothing gets silently
changed without you knowing.

HOW TO RUN THIS:
    python3 clean_data.py

You only need to run this again if you update one of the raw Excel files.
app.py never touches the raw Excel files directly - it only reads the clean
CSVs this script produces.
"""

import os
import re
import pandas as pd

# ---------------------------------------------------------------------------
# SETTINGS - where files live. You shouldn't need to change these.
# ---------------------------------------------------------------------------
RAW_DIR = "data/raw"
CLEAN_DIR = "data/clean"

FRESHERS_FILE = os.path.join(RAW_DIR, "Freshers_Campaign_-_2025.xlsx")
FRESHERS_SHEET = "HYD"

CRM_FILE = os.path.join(RAW_DIR, "CRM_-_RB_TS__2026_.xlsx")
FEST_SHEET = "2025 Fest Tracker"
EVENTS_SHEET = "3P Events"

os.makedirs(CLEAN_DIR, exist_ok=True)

# This list collects plain-English notes as we go, so we can write them all
# to data_quality_report.txt at the end.
report_lines = []


def log(line=""):
    """Add a line to the quality report AND print it to the screen."""
    report_lines.append(line)
    print(line)


# ---------------------------------------------------------------------------
# HELPER 1: Standardize a college/institution name
# ---------------------------------------------------------------------------
def build_name_lookup(raw_names):
    """
    Takes a list of raw college names (with typos/casing/whitespace issues)
    and returns a dictionary that maps EVERY raw variant to one clean,
    consistent version of that name.

    How it decides the "clean" version: it groups names that are the same
    once you ignore extra spaces and capitalization, then picks whichever
    exact spelling appeared most often in the real data as the canonical one.
    """
    groups = {}  # normalized_key -> {raw_name: count}
    for name in raw_names:
        if not isinstance(name, str) or name.strip() == "":
            continue
        # normalized key: lowercase, collapse all whitespace, strip ends
        key = re.sub(r"\s+", " ", name.strip().lower())
        groups.setdefault(key, {})
        groups[key][name] = groups[key].get(name, 0) + 1

    lookup = {}
    collapsed_report = []
    for key, variants in groups.items():
        # pick the most common spelling as the canonical version
        canonical = max(variants, key=variants.get).strip()
        # tidy the canonical spelling: collapse internal whitespace
        canonical = re.sub(r"\s+", " ", canonical)
        for variant in variants:
            lookup[variant] = canonical
        if len(variants) > 1:
            collapsed_report.append((canonical, list(variants.keys())))
    return lookup, collapsed_report


# ---------------------------------------------------------------------------
# HELPER 2: Parse a date safely, flagging anything we can't trust
# ---------------------------------------------------------------------------
def parse_date_safely(value):
    """
    Takes one raw date cell (could be a real date, a string, or blank) and
    returns (parsed_date_or_None, status_flag).

    status_flag is one of: "ok", "missing", "unparseable"
    We NEVER guess a date if it's not clearly parseable - we flag it instead.
    """
    if pd.isna(value) or value == "":
        return None, "missing"

    if isinstance(value, pd.Timestamp):
        return value.date(), "ok"

    try:
        # dayfirst=True because this data uses DD/MM/YYYY, matching the
        # sheet's own text-date entries (e.g. "21/08/25")
        parsed = pd.to_datetime(value, dayfirst=True, errors="raise")
        return parsed.date(), "ok"
    except Exception:
        return None, "unparseable"


def fill_missing_text(series):
    """Replace blank/NaN text cells with the label 'Not Reported'."""
    return series.apply(
        lambda v: "Not Reported" if (pd.isna(v) or str(v).strip() == "") else str(v).strip()
    )


def fill_missing_number(series):
    """
    Replace blank/NaN number cells with the text 'Unknown' - we keep this
    column as text after this, since 'Unknown' isn't a number. This keeps us
    from ever inventing a number that wasn't really there.
    """
    return series.apply(lambda v: "Unknown" if pd.isna(v) else v)


log("=" * 70)
log("DATA QUALITY REPORT")
log("Generated by clean_data.py")
log("=" * 70)

# ===========================================================================
# FILE 1: FRESHERS CAMPAIGN  ->  activations_clean.csv
# ===========================================================================
log("")
log("-" * 70)
log("FILE 1: Freshers Campaign (sheet 'HYD') -> activations_clean.csv")
log("-" * 70)

raw = pd.read_excel(FRESHERS_FILE, sheet_name=FRESHERS_SHEET)
total_rows_in_sheet = len(raw)

# The sheet has a lot of fully blank padding rows below the real data.
# A row only counts as "real" if it has a college name.
df = raw[raw["COLLEGE NAME"].notna()].copy()
blank_rows_dropped = total_rows_in_sheet - len(df)
log(f"Sheet had {total_rows_in_sheet} total rows; {blank_rows_dropped} were "
    f"completely blank padding rows and were dropped.")
log(f"{len(df)} real activation rows remain.")

# --- Standardize college names ---
lookup, collapsed = build_name_lookup(df["COLLEGE NAME"].tolist())
df["college_name_clean"] = df["COLLEGE NAME"].map(lookup)
log("")
log(f"College name cleanup: {len(collapsed)} college name(s) had multiple "
    f"spellings that were merged into one consistent version:")
for canonical, variants in collapsed:
    log(f"  - \"{canonical}\"  <-  {variants}")

# --- Parse dates ---
parsed = df["DATE OF ACTIVATION/HACK"].apply(parse_date_safely)
df["activation_date"] = parsed.apply(lambda t: t[0])
df["activation_date_status"] = parsed.apply(lambda t: t[1])
missing_dates = (df["activation_date_status"] == "missing").sum()
bad_dates = (df["activation_date_status"] == "unparseable").sum()
log("")
log(f"Date parsing: {missing_dates} row(s) had a missing activation date, "
    f"{bad_dates} row(s) had a date that could not be understood (flagged, "
    f"not guessed).")

# --- Fill / flag missing values instead of inventing numbers ---
df["owner_sm_name"] = fill_missing_text(df["SM NAME"])
df["primary_or_secondary"] = fill_missing_text(df["Primary/Secondary"])
df["integration_plan"] = fill_missing_text(df["INTEGRATION PLAN"])
df["assets_required"] = fill_missing_text(df["ASSETS REQUIRED"])
df["asset_qty"] = fill_missing_number(df["ASSET QTY"])
df["budget"] = fill_missing_number(df["BUDGET"])

missing_budget = (df["budget"] == "Unknown").sum()
missing_qty = (df["asset_qty"] == "Unknown").sum()
log("")
log(f"Missing values flagged (not invented): {missing_budget} row(s) with "
    f"no BUDGET, {missing_qty} row(s) with no ASSET QTY. These are marked "
    f"'Unknown' rather than left blank or estimated.")

# --- Estimated budget (user-provided assumption, NOT real reported data) ---
# Where the real BUDGET is missing but ASSET QTY is a known number, we
# calculate what the budget WOULD be at Rs. 125 per unit. This is clearly
# kept as a separate column - it is an estimate, not a substitute for the
# real (missing) budget figure, and is not used to decide dashboard status.
RS_PER_UNIT = 125

def estimate_budget(row):
    if row["budget"] != "Unknown":
        return "Not Applicable - Real Budget Reported"
    qty = row["asset_qty"]
    if qty == "Unknown":
        return "Cannot Estimate - Asset Qty Also Missing"
    try:
        return round(float(qty) * RS_PER_UNIT, 2)
    except (ValueError, TypeError):
        return "Cannot Estimate - Asset Qty Also Missing"

df["estimated_budget_at_rs125_per_unit"] = df.apply(estimate_budget, axis=1)
estimated_count = df["estimated_budget_at_rs125_per_unit"].apply(
    lambda v: isinstance(v, (int, float))
).sum()
log("")
log(f"Budget estimation: {estimated_count} row(s) with a missing real budget "
    f"but a known asset quantity got an ESTIMATED budget at Rs. {RS_PER_UNIT} "
    f"per unit (column: estimated_budget_at_rs125_per_unit). This is an "
    f"assumption you provided, not data from the original spreadsheet, and "
    f"is kept separate from the real 'budget' column for that reason.")

activations_clean = df[[
    "college_name_clean", "primary_or_secondary", "owner_sm_name",
    "activation_date", "activation_date_status", "integration_plan",
    "assets_required", "asset_qty", "budget", "estimated_budget_at_rs125_per_unit",
]].rename(columns={"college_name_clean": "college_name"})

activations_clean.to_csv(os.path.join(CLEAN_DIR, "activations_clean.csv"), index=False)
log("")
log(f"Wrote {len(activations_clean)} rows to activations_clean.csv")

# ===========================================================================
# FILE 2: FEST TRACKER  ->  fest_tracker_clean.csv
# ===========================================================================
log("")
log("-" * 70)
log("FILE 2: CRM Fest Tracker (sheet '2025 Fest Tracker') -> fest_tracker_clean.csv")
log("-" * 70)

# The real header row is the SECOND row of this sheet (the first row is a
# stray title), so header=1 tells pandas to use that row for column names.
raw = pd.read_excel(CRM_FILE, sheet_name=FEST_SHEET, header=1)
total_rows_in_sheet = len(raw)

df = raw[raw["INSTITUTION / COLLEGE NAME"].notna()].copy()
blank_rows_dropped = total_rows_in_sheet - len(df)
log(f"Sheet had {total_rows_in_sheet} total rows; {blank_rows_dropped} were "
    f"blank padding rows and were dropped.")
log(f"{len(df)} real festival rows remain.")

lookup, collapsed = build_name_lookup(df["INSTITUTION / COLLEGE NAME"].tolist())
df["institution_clean"] = df["INSTITUTION / COLLEGE NAME"].map(lookup)
log("")
log(f"Institution name cleanup: {len(collapsed)} institution name(s) had "
    f"multiple spellings merged into one:")
for canonical, variants in collapsed:
    log(f"  - \"{canonical}\"  <-  {variants}")

# --- Standardize TIER (had case + whitespace + placeholder "-" issues) ---
def clean_tier(value):
    if pd.isna(value):
        return "Not Reported"
    text = str(value).strip().upper()
    if text in ("-", ""):
        return "Not Reported"
    # normalize "TIER A" / "TIERA" / "TIER  A" -> "TIER A"
    match = re.match(r"TIER\s*([ABCD])", text)
    if match:
        return f"TIER {match.group(1)}"
    return text

df["tier_clean"] = df["TIER"].apply(clean_tier)
tier_counts_before = df["TIER"].astype(str).str.strip().nunique()
tier_counts_after = df["tier_clean"].nunique()
log("")
log(f"TIER cleanup: collapsed {tier_counts_before} raw variants (mixed case, "
    f"stray spaces, '-' placeholders) down to {tier_counts_after} consistent "
    f"values.")

# --- "Lost to competition" flag - keep the free-text reason, don't invent ---
lost_col = "HAVE WE LOST OUT ON THIS FESTIVAL THIS YEAR? IF YES, THEN MENTION THE REASON\n Example: Taken over by competition (specify who)/ Red Bull banned on campus"
df["lost_to_competition_note"] = fill_missing_text(df[lost_col])
df["lost_to_competition_flag"] = df["lost_to_competition_note"].apply(
    lambda v: True if v.strip().lower().startswith("yes") else False
)
lost_count = df["lost_to_competition_flag"].sum()
log("")
log(f"{lost_count} festival(s) are flagged as lost to competition this year "
    f"(based on the tracker's own 'have we lost this festival' notes).")

df["competitor_activity_note"] = fill_missing_text(
    df["IF APPLICABLE, HOW HAS COMPETITION SUPPORTED THIS FESTIVAL?"]
)
df["fest_name"] = fill_missing_text(df["FEST NAME"])
df["month"] = fill_missing_text(df["MONTH"])
df["fest_type"] = fill_missing_text(df["FEST TYPE"])
df["crowd_approx"] = fill_missing_number(df["CROWD APPROX."])
df["total_sales"] = fill_missing_number(df["TOTAL SALES"])
df["planned_support_category"] = fill_missing_text(
    df["PLANNED SUPPORT CATEGORY FOR 2025\n  (A OR B OR C OR D)\n A. trials+tools+sales+add engagement or activation \n B. Trials+tools+sales\n C. Trials+tools\n D. Trials"]
)
df["region"] = fill_missing_text(df["REGION"])
df["city"] = fill_missing_text(df["CITY"])

fest_tracker_clean = df[[
    "region", "city", "institution_clean", "fest_name", "month",
    "fest_type", "crowd_approx", "total_sales", "tier_clean",
    "planned_support_category", "lost_to_competition_flag",
    "lost_to_competition_note", "competitor_activity_note",
]].rename(columns={"institution_clean": "institution_name", "tier_clean": "tier"})

fest_tracker_clean.to_csv(os.path.join(CLEAN_DIR, "fest_tracker_clean.csv"), index=False)
log("")
log(f"Wrote {len(fest_tracker_clean)} rows to fest_tracker_clean.csv")

# ===========================================================================
# FILE 3: 3P EVENTS  ->  events_3p_clean.csv
# ===========================================================================
log("")
log("-" * 70)
log("FILE 3: CRM 3P Events (sheet '3P Events') -> events_3p_clean.csv")
log("-" * 70)

raw = pd.read_excel(CRM_FILE, sheet_name=EVENTS_SHEET)
total_rows_in_sheet = len(raw)

df = raw[raw["Name of Event"].notna()].copy()
blank_rows_dropped = total_rows_in_sheet - len(df)
log(f"Sheet had {total_rows_in_sheet} total rows; {blank_rows_dropped} were "
    f"blank padding rows and were dropped.")
log(f"{len(df)} real event rows remain.")

df["event_name"] = fill_missing_text(df["Name of Event"])
df["city"] = fill_missing_text(df["City"])
df["discipline"] = fill_missing_text(df["Discipline"])
df["category"] = fill_missing_text(df["Culture/Sport/Student"])

# Cost = sampling/seeding spend + event support spend (both are cost inputs)
sampling_cost = pd.to_numeric(df["Sampling/\nSeeding"], errors="coerce")
support_cost = pd.to_numeric(df["Event Support"], errors="coerce")
df["_sampling_cost_num"] = sampling_cost
df["_support_cost_num"] = support_cost
df["total_cost"] = sampling_cost.fillna(0) + support_cost.fillna(0)
cost_fully_missing = ((sampling_cost.isna()) & (support_cost.isna())).sum()

df["cans_sold"] = pd.to_numeric(df["Sales Numbers (in cans)"], errors="coerce")
df["people_present"] = pd.to_numeric(df["People Present"], errors="coerce")
missing_cans = df["cans_sold"].isna().sum()
missing_people = df["people_present"].isna().sum()

log("")
log(f"Cost data: {cost_fully_missing} row(s) had no cost figures at all "
    f"(both Sampling/Seeding and Event Support blank) - these will be "
    f"excluded from the ROI ranking rather than treated as zero-cost.")
log(f"Sales data: {missing_cans} row(s) missing cans-sold figures, "
    f"{missing_people} row(s) missing people-present figures - excluded "
    f"from the relevant ROI calculations rather than estimated.")

# Mark rows that can't be used for ROI math instead of silently including them
df["has_cost_data"] = ~((sampling_cost.isna()) & (support_cost.isna()))
df["has_cans_data"] = df["cans_sold"].notna()
df["has_people_data"] = df["people_present"].notna()

df["start_date"] = pd.to_datetime(df["Start Date"], errors="coerce").dt.date
df["month"] = fill_missing_text(df["Month"])
df["year"] = fill_missing_text(df["Year"])

events_3p_clean = df[[
    "event_name", "city", "category", "discipline", "year", "month",
    "start_date", "total_cost", "has_cost_data", "cans_sold",
    "has_cans_data", "people_present", "has_people_data",
]]

events_3p_clean.to_csv(os.path.join(CLEAN_DIR, "events_3p_clean.csv"), index=False)
log("")
log(f"Wrote {len(events_3p_clean)} rows to events_3p_clean.csv")

# ===========================================================================
# WRITE THE REPORT FILE
# ===========================================================================
log("")
log("=" * 70)
log("DONE. All three clean CSVs are in data/clean/.")
log("=" * 70)

report_path = os.path.join(CLEAN_DIR, "data_quality_report.txt")
with open(report_path, "w") as f:
    f.write("\n".join(report_lines))

print(f"\nFull report also saved to: {report_path}")
